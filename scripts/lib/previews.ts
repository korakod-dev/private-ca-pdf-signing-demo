// SVG preview generator for the sample documents (spec 7.5: fictional memo, 1-3 pages, DEMO watermark on every page).
// Pure and deterministic: the same fixtures always produce byte-identical SVGs, so the committed files can be
// compared against a fresh run (see scripts/__tests__/previews.test.ts).
// SVG notes: presentation attributes only (no <style>, no scripts, no external references, no web fonts), so the
// files are safe under the production CSP and as <img> sources. Thai text uses system fonts.
import type { CertFixture, FixtureBundle, FixtureDocument } from '../../src/contracts/fixtures';
import { commonName } from './real-data-detector';

const W = 595; // A4 at 72 dpi
const H = 842;
const FONT = "Noto Sans Thai, Thonburi, Tahoma, 'Sarabun', sans-serif";

/** Escapes text for use in SVG element content. */
function esc(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

function text(x: number, y: number, size: number, content: string, extra = ''): string {
  return `<text x="${x}" y="${y}" font-family="${esc(FONT)}" font-size="${size}" fill="#222222"${extra ? ` ${extra}` : ''}>${esc(content)}</text>`;
}

/** Grey bars standing in for lines of body text. Widths vary deterministically (no randomness). */
function placeholderLines(x: number, y: number, count: number, width: number): string {
  const out: string[] = [];
  for (let i = 0; i < count; i += 1) {
    const w = width - ((i * 37) % 90) - (i === count - 1 ? 120 : 0);
    out.push(`<rect x="${x}" y="${y + i * 18}" width="${w}" height="7" rx="3" fill="#d4d7dc"/>`);
  }
  return out.join('\n  ');
}

/** Display name for a signature box: the CN of the signer certificate (fictional persona or the DEMO self-signed one). */
function signerLabel(certs: CertFixture[], serial: string): string {
  const cert = certs.find((c) => c.serial === serial);
  return (cert && commonName(cert.subject)) || 'ผู้ลงนาม (สมมติ)';
}

function watermark(): string {
  return [
    `<g transform="rotate(-35 ${W / 2} ${H / 2})" text-anchor="middle" fill="#c0392b" fill-opacity="0.16" font-family="${esc(FONT)}" font-weight="bold">`,
    `  <text x="${W / 2}" y="${H / 2 + 40}" font-size="170">DEMO</text>`,
    `  <text x="${W / 2}" y="${H / 2 + 90}" font-size="34">ไม่ใช่เอกสารจริง</text>`,
    '</g>',
  ].join('\n  ');
}

/** Renders one preview page (page is 1-based). */
export function renderPreviewSvg(doc: FixtureDocument, page: number, certs: CertFixture[]): string {
  const total = doc.previews.length;
  const parts: string[] = [];

  if (page === 1) {
    parts.push(text(W / 2, 90, 26, 'บันทึกข้อความ', 'text-anchor="middle" font-weight="bold"'));
    parts.push(text(60, 135, 14, 'ส่วนราชการ  Korakod Lab DEMO (หน่วยงานสมมติ)'));
    parts.push(text(60, 160, 14, `ที่  DEMO-${doc.id}/2569`));
    parts.push(text(60, 185, 14, `เรื่อง  ${doc.title_th}`));
    parts.push('<line x1="60" y1="198" x2="535" y2="198" stroke="#999999" stroke-width="1"/>');
    parts.push(text(60, 232, 14, 'เรียน  ผู้เกี่ยวข้อง (สมมติ)'));
    parts.push(placeholderLines(60, 258, 9, 475));
    parts.push(text(60, 450, 12, 'เอกสารนี้เป็นตัวอย่างสำหรับการสาธิตเท่านั้น เนื้อหาทั้งหมดเป็นข้อความสมมติ', 'fill-opacity="0.75"'));
    parts.push(placeholderLines(60, 475, 6, 475));
  } else {
    parts.push(placeholderLines(60, 90, 14, 475));
  }

  if (doc.encrypted && page === 1) {
    parts.push(text(60, 620, 13, 'ไฟล์ตัวอย่างนี้จำลองว่าเป็น PDF ที่เข้ารหัส', 'fill-opacity="0.8"'));
  }
  if (doc.pages > total && page === total) {
    parts.push(text(60, 620, 13, `ตัวอย่างนี้แสดงเพียง ${total} หน้าแรก จากทั้งหมด ${doc.pages} หน้า (จำลอง)`, 'fill-opacity="0.8"'));
  }

  // Signature boxes on the last previewed page (one per signature field).
  if (page === total && doc.signature_fields.length > 0) {
    doc.signature_fields.forEach((field, i) => {
      const x = 60 + i * 245;
      const sig = doc.signatures.find((s) => s.field === field);
      parts.push(`<rect x="${x}" y="660" width="230" height="80" fill="none" stroke="#7a7f87" stroke-width="1" stroke-dasharray="4 3"/>`);
      parts.push(text(x + 8, 680, 11, `ช่องลายมือชื่อ: ${field}`, 'fill-opacity="0.7"'));
      parts.push(text(x + 8, 716, 13, sig ? signerLabel(certs, sig.signer_cert_serial) : '(ยังไม่ได้ลงนาม)', 'font-weight="bold"'));
    });
  }

  parts.push(text(W / 2, 810, 11, `หน้า ${page} / ${doc.pages}  ·  ${doc.file_name}  ·  DEMO`, 'text-anchor="middle" fill-opacity="0.6"'));

  return [
    '<?xml version="1.0" encoding="UTF-8"?>',
    '<!-- DEMO fixture preview. Generated by scripts/gen-previews.ts; do not edit by hand. All content is fictional. -->',
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" role="img" aria-label="${esc(`ตัวอย่างเอกสาร DEMO ${doc.id} หน้า ${page}`)}">`,
    `  <title>${esc(`DEMO ${doc.id} page ${page}`)}</title>`,
    `  <rect width="${W}" height="${H}" fill="#ffffff"/>`,
    `  <rect x="0.5" y="0.5" width="${W - 1}" height="${H - 1}" fill="none" stroke="#c9ccd1"/>`,
    ...parts.map((p) => `  ${p}`),
    `  ${watermark()}`,
    '</svg>',
    '',
  ].join('\n');
}

/** Maps every preview path ("/previews/D01-p1.svg") to its SVG content for the whole bundle. */
export function renderAllPreviews(bundle: FixtureBundle): Map<string, string> {
  const out = new Map<string, string>();
  for (const doc of bundle.documents) {
    doc.previews.forEach((path, i) => out.set(path, renderPreviewSvg(doc, i + 1, bundle.certs)));
  }
  return out;
}
