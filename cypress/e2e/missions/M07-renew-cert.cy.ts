// M7: aree renews the certificate that has 21 days left. Proofing was < 3 years ago, so no in-person step (A9):
// the new cert is Issued, finalize makes it Active, the old one becomes "superseded" (Revoked with reason superseded, A10).
// Pages used: /certs (sub-task F), /missions (G). The renew button asks the new key's passphrase first (QA F27, A42).
import { ROUTES } from '../../../src/contracts/routes';
import { TID } from '../../../src/contracts/testids';
import { AREE_CERT, expectMissionDone, gotoPage, missionAtEachViewport, rowSelector, startAs } from '../../support/missions';

const GOOD_PASSPHRASE = 'twelve-chars-or-more!';

describe('M7: renew a certificate', () => {
  missionAtEachViewport('renew -> new cert Issued -> finalize -> Active, old cert superseded', () => {
    startAs('u-aree');
    expectMissionDone('M7', false);

    gotoPage('certs', ROUTES.certs);
    cy.tid(TID.certs.row(AREE_CERT)).should('have.attr', 'data-state', 'Active');
    cy.tid(TID.certs.renew(AREE_CERT)).click();

    // Renewal makes a NEW key, so the page asks its passphrase first (F27): masked, >= 12 characters, never shown again.
    cy.tid(TID.certs.passphraseDialog).should('be.visible');
    cy.tid(TID.certs.passphraseInput).should('have.attr', 'type', 'password').type('elevenchar1');
    cy.tid(TID.certs.passphraseSubmit).click();
    cy.tid(TID.certs.passphraseError).should('be.visible'); // 11 characters: asked again, nothing renewed yet
    cy.tid(TID.certs.passphraseInput).clear().type(GOOD_PASSPHRASE);
    cy.a11y();
    cy.tid(TID.certs.passphraseSubmit).click();
    cy.tid(TID.certs.passphraseDialog).should('not.exist');
    cy.get('body').should('not.contain.text', GOOD_PASSPHRASE);

    // The new certificate (serial generated by the engine) shows up as Issued with a finalize action.
    const rows = rowSelector(TID.certs.row);
    cy.get(`${rows}[data-state="Issued"]`).should('have.length', 1);
    cy.a11y();
    cy.get(`[data-testid^="${TID.certs.finalize('')}"]`).first().click();

    // Now: exactly one Active cert (the new one) and the old one is superseded.
    cy.get(`${rows}[data-state="Active"]`).should('have.length', 1);
    cy.get(`${rows}[data-state="Issued"]`).should('not.exist');
    cy.tid(TID.certs.row(AREE_CERT)).should('have.attr', 'data-state', 'Revoked').and('contain.text', 'superseded');
    cy.a11y();

    expectMissionDone('M7', true);
  });
});
