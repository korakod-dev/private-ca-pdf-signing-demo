// M2: nattapon requests a certificate from scratch, admin-a approves it in person, nattapon finalizes it.
// Pages used: /certs/request, /certs, /mailbox (sub-task F), /admin/requests (F), /missions (G),
// terminal (D) + `pki-tool` (F).
import { ROUTES } from '../../../src/contracts/routes';
import { TID } from '../../../src/contracts/testids';
import {
  MANOP_REQUEST,
  answerPrompt,
  confirmMfa,
  expectMissionDone,
  gotoPage,
  missionAtEachViewport,
  rowId,
  rowSelector,
  selectFirstOption,
  startAs,
  switchTo,
  waitForIdle,
} from '../../support/missions';

const SHORT_PASSPHRASE = 'elevenchar1'; // 11 characters: must be rejected (passphrase needs >= 12)
const GOOD_PASSPHRASE = 'twelve-chars-or-more!';

describe('M2: request a certificate from the start', () => {
  missionAtEachViewport('init -> appointment -> submit -> approve in person -> finalize -> Active', () => {
    startAs('u-nattapon');
    expectMissionDone('M2', false);

    // --- nattapon: key + CSR in the simulated terminal ---
    gotoPage('certRequest', ROUTES.certRequest);
    cy.terminalRun('pki-tool init --name "ณัฐพล ทองดี" --email nattapon@lab.korakod.dev');
    answerPrompt(SHORT_PASSPHRASE, { secret: true }); // too short -> asked again
    answerPrompt(GOOD_PASSPHRASE, { secret: true }); // accepted
    waitForIdle();
    cy.tid(TID.terminal.output).should('contain.text', 'CSR');
    // The passphrase stays on the "machine": it is never printed back.
    cy.get('body').should('not.contain.text', GOOD_PASSPHRASE).and('not.contain.text', SHORT_PASSPHRASE);

    // --- appointment + submit: the request waits for the in-person check ---
    selectFirstOption(TID.request.appointmentSelect);
    cy.tid(TID.request.submit).click();
    cy.tid(TID.request.status).should(($status) => {
      const shown = `${$status.attr('data-state') ?? ''} ${$status.text()}`;
      expect(shown, 'request status').to.match(/awaitingInPerson|พบตัว|นัดหมาย/);
    });
    cy.a11y();

    // --- admin-a: tick the five in-person checks, approve with MFA ---
    switchTo('a-admin-a');
    gotoPage('adminRequests', ROUTES.adminRequests);
    // nattapon's request is the awaiting row that is not manop's seeded one (its id is generated by the engine).
    const awaiting = rowSelector(TID.adminRequests.row, '[data-state="awaitingInPerson"]');
    cy.get(awaiting)
      .not(`[data-testid="${TID.adminRequests.row(MANOP_REQUEST)}"]`)
      .first()
      .then(($row) => {
        const id = rowId(TID.adminRequests.row, $row);
        [1, 2, 3, 4, 5].forEach((n) => cy.tid(TID.adminRequests.checklist(id, n)).check());
        cy.tid(TID.adminRequests.approve(id)).should('not.be.disabled').click();
        confirmMfa();
        cy.tid(TID.adminRequests.row(id)).should('have.attr', 'data-state', 'approved');
      });
    cy.a11y();

    // --- nattapon: finalize the issued certificate ---
    switchTo('u-nattapon');
    gotoPage('certs', ROUTES.certs);
    cy.get(`[data-testid^="${TID.certs.finalize('')}"]`).first().click();
    cy.get(rowSelector(TID.certs.row, '[data-state="Active"]')).should('have.length.at.least', 1);

    // --- the approval mail is in the mailbox ---
    gotoPage('mailbox', ROUTES.mailbox);
    cy.tid(TID.mailbox.list).should('contain.text', 'ใบรับรองของคุณได้รับอนุมัติแล้ว');

    expectMissionDone('M2', true);
  });
});
